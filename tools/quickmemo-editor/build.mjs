import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const project = fileURLToPath(new URL('.', import.meta.url));
const output = process.argv[2] ?? fileURLToPath(new URL('../../vivaldi-notes/vendor/', import.meta.url));
const bundle = await build({
  absWorkingDir: project,
  entryPoints: ['exports.js'],
  outfile: 'codemirror.js',
  bundle: true,
  format: 'esm',
  target: 'chrome116',
  minify: true,
  write: false,
  metafile: true,
  legalComments: 'none',
  banner: { js: '// Generated by tools/quickmemo-editor. See LICENSES.txt for third-party notices.' },
});

const packages = new Set();
for (const input of Object.keys(bundle.metafile.inputs)) {
  const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (match) packages.add(match[1]);
}
const notices = [];
for (const name of [...packages].sort()) {
  const directory = resolve(project, name);
  const pkg = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
  const license = (await readdir(directory)).find((file) => /^licen[cs]e(\.|$)/i.test(file));
  if (!license) throw new Error(`Missing license for ${pkg.name}`);
  notices.push(`${pkg.name} ${pkg.version}\n\n${(await readFile(resolve(directory, license), 'utf8')).trimEnd()}`);
}

await mkdir(output, { recursive: true });
await writeFile(resolve(output, 'codemirror.js'), bundle.outputFiles[0].contents);
await writeFile(resolve(output, 'LICENSES.txt'), `${notices.join('\n\n---\n\n')}\n`);
